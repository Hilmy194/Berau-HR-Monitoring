// Gabungan seluruh jadwal
export const ALL_CADENCE_ITEMS: CadenceScheduleItem[] = [
  ...CADENCE_DEVELOPMENT_PROGRAMS,
  ...CADENCE_TRAININGS,
];

// Helper: Cari seluruh agenda yang aktif pada suatu tanggal ISO ("YYYY-MM-DD")
export function getAgendaForDate(targetIso: string, itemsList: CadenceScheduleItem[] = ALL_CADENCE_ITEMS): {
  developmentPrograms: CadenceScheduleItem[];
  trainings: CadenceScheduleItem[];
  totalEvents: number;
} {
  const d = new Date(targetIso);
  const targetTime = d.getTime();

  const matchingItems = itemsList.filter((item) => {
    const start = new Date(item.startIso).getTime();
    const end = new Date(item.endIso).getTime();
    return targetTime >= start && targetTime <= end;
  });

  const developmentPrograms = matchingItems.filter(
    (item) => item.category === "EXCLUSIVE_DP" || item.category === "INCLUSIVE_DP" || item.category === "EVENT_PROJECT"
  );
  const trainings = matchingItems.filter((item) => item.category === "TRAINING_CATALOG");

  return {
    developmentPrograms,
    trainings,
    totalEvents: matchingItems.length,
  };
}

// Helper: Cari seluruh agenda untuk bulan tertentu ("YYYY-MM")
export function getAgendaForMonth(yearMonth: string, itemsList: CadenceScheduleItem[] = ALL_CADENCE_ITEMS): CadenceScheduleItem[] {
  return itemsList.filter((item) => item.activeMonths.includes(yearMonth));
}
